"""
Train Arc2Face UNet LoRA with projected identity conditioning.

Fix 4: when real_image_paths is provided, real photos are FFHQ-aligned and
used as primary training targets (better identity than synthetic images).
Synthetic images in train_data_dir are used as supplementary diversity.
Conditioning uses arc2face_embedding (correct space) when available.
"""
from __future__ import annotations
from pathlib import Path

import numpy as np

from .synthesizer import Arc2FaceSynthesizer


def _align_to_ffhq_512(image_path: str | Path) -> "np.ndarray | None":
    """
    Load image, detect largest face, return FFHQ-aligned 512x512 BGR crop.
    Falls back to None if no face detected (caller uses center-crop fallback).
    """
    from PIL import Image
    import cv2
    from faceswap.core.detector import detect_largest
    from faceswap.core.aligner import estimate_transform

    with Image.open(image_path) as img:
        frame_bgr = np.asarray(img.convert("RGB"))[:, :, ::-1].copy()
    face = detect_largest(frame_bgr)
    if face is None:
        return None
    M = estimate_transform(face.kps, 512)
    return cv2.warpAffine(frame_bgr, M, (512, 512), borderMode=cv2.BORDER_REFLECT)


def train_lora(train_data_dir: str | Path,
               output_dir: str | Path,
               embedding,
               real_image_paths: list[str | Path] | None = None,
               arc2face_embedding: "np.ndarray | None" = None,
               max_train_steps: int = 800,
               rank: int = 16,
               learning_rate: float = 1e-4) -> Path:
    """
    Fine-tune the Arc2Face UNet LoRA.

    real_image_paths: when provided, real user photos are FFHQ-aligned and
      prepended to the training set for better identity fidelity (Fix 4).
    arc2face_embedding: antelopev2 embedding for Arc2Face conditioning (Fix 2);
      falls back to buffalo_l embedding when None.
    train_data_dir: synthetic images generated by Arc2FaceSynthesizer.
    """
    if max_train_steps < 1 or rank < 1:
        raise ValueError("Training steps and LoRA rank must be positive")

    # Build image list: real photos first (higher identity signal), then synthetic
    all_images: list[Path] = []
    if real_image_paths:
        all_images.extend(Path(p) for p in real_image_paths)
    if train_data_dir is not None:
        synth_dir = Path(train_data_dir)
        if synth_dir.exists():
            all_images.extend(sorted(
                p for p in synth_dir.iterdir()
                if p.suffix.lower() in {".png", ".jpg", ".jpeg"}
            ))
    if not all_images:
        raise ValueError("No training images found")

    # Conditioning: arc2face space preferred (correct for Arc2Face UNet)
    cond_emb = arc2face_embedding if arc2face_embedding is not None else embedding

    synthesizer = Arc2FaceSynthesizer()
    try:
        return _train(synthesizer, all_images, Path(output_dir), cond_emb,
                      real_count=len(real_image_paths) if real_image_paths else 0,
                      steps=max_train_steps, rank=rank, learning_rate=learning_rate)
    finally:
        synthesizer.close()


def _load_image_as_latent(path: Path, vae, device, dtype, is_real: bool):
    """Load one image → VAE latent. Real photos get FFHQ alignment; synthetics get center crop."""
    import torch
    from PIL import Image, ImageOps

    if is_real:
        aligned_bgr = _align_to_ffhq_512(path)
        if aligned_bgr is not None:
            rgb = aligned_bgr[:, :, ::-1]
            pixels = np.asarray(rgb, dtype=np.float32) / 127.5 - 1
        else:
            # Fallback: center crop
            with Image.open(path) as img:
                img = ImageOps.fit(img.convert("RGB"), (512, 512))
            pixels = np.asarray(img, dtype=np.float32) / 127.5 - 1
    else:
        with Image.open(path) as img:
            img = ImageOps.fit(img.convert("RGB"), (512, 512))
        pixels = np.asarray(img, dtype=np.float32) / 127.5 - 1

    tensor = torch.from_numpy(pixels).permute(2, 0, 1).unsqueeze(0).to(device, dtype)
    return (vae.encode(tensor).latent_dist.sample() * vae.config.scaling_factor).cpu()


def _train(synthesizer, images, output_dir, embedding,
           real_count, steps, rank, learning_rate):
    import torch
    import torch.nn.functional as F
    from diffusers import DDPMScheduler, StableDiffusionPipeline
    from diffusers.utils import convert_state_dict_to_diffusers
    from peft import LoraConfig
    from peft.utils import get_peft_model_state_dict

    torch.manual_seed(42)
    prompt = synthesizer.prompt_embeddings(embedding).detach()
    pipeline = synthesizer._pipeline
    unet, vae = pipeline.unet, pipeline.vae
    unet.requires_grad_(False)
    vae.requires_grad_(False)
    pipeline.text_encoder.requires_grad_(False)
    pipeline.text_encoder.to("cpu")
    scheduler = DDPMScheduler.from_config(pipeline.scheduler.config)
    device, dtype = synthesizer._device, synthesizer._dtype

    latents = []
    with torch.no_grad():
        for i, path in enumerate(images):
            is_real = i < real_count
            latents.append(_load_image_as_latent(path, vae, device, dtype, is_real))
    vae.to("cpu")

    unet.add_adapter(LoraConfig(r=rank, lora_alpha=rank, init_lora_weights="gaussian",
                                target_modules=["to_q", "to_k", "to_v", "to_out.0"]))
    parameters = [p for p in unet.parameters() if p.requires_grad]
    for parameter in parameters:
        parameter.data = parameter.data.float()
    unet.enable_gradient_checkpointing()
    unet.train()
    optimizer = torch.optim.AdamW(parameters, lr=learning_rate)
    use_amp = device.startswith("cuda")
    scaler = torch.cuda.amp.GradScaler(enabled=use_amp)

    # Sample real photos more frequently: they carry stronger identity signal
    if real_count > 0 and real_count < len(latents):
        real_weight = 3.0  # real photos sampled 3× as often as synthetics
        weights = np.array(
            [real_weight] * real_count + [1.0] * (len(latents) - real_count),
            dtype=np.float32)
        weights /= weights.sum()
        step_indices = np.random.default_rng(42).choice(
            len(latents), size=steps, p=weights)
    else:
        step_indices = np.arange(steps, dtype=np.int64) % len(latents)

    for step, idx in enumerate(step_indices):
        latent = latents[idx].to(device, dtype)
        noise = torch.randn_like(latent)
        timestep = torch.randint(0, scheduler.config.num_train_timesteps, (1,), device=device)
        noisy = scheduler.add_noise(latent, noise, timestep)
        noisy.requires_grad_(True)
        if scheduler.config.prediction_type == "epsilon":
            target = noise
        elif scheduler.config.prediction_type == "v_prediction":
            target = scheduler.get_velocity(latent, noise, timestep)
        else:
            raise ValueError(f"Unsupported prediction type: {scheduler.config.prediction_type}")
        optimizer.zero_grad(set_to_none=True)
        with torch.autocast(device_type="cuda" if use_amp else "cpu", enabled=use_amp):
            prediction = unet(noisy, timestep, encoder_hidden_states=prompt).sample
            loss = F.mse_loss(prediction.float(), target.float())
        scaler.scale(loss).backward()
        scaler.unscale_(optimizer)
        torch.nn.utils.clip_grad_norm_(parameters, 1.0)
        scaler.step(optimizer)
        scaler.update()
        if (step + 1) % 50 == 0:
            print(f"[trainer] {step + 1}/{steps}: loss={loss.item():.4f}")

    output_dir.mkdir(parents=True, exist_ok=True)
    state = convert_state_dict_to_diffusers(get_peft_model_state_dict(unet))
    StableDiffusionPipeline.save_lora_weights(
        str(output_dir), unet_lora_layers=state, safe_serialization=True,
    )
    return output_dir / "pytorch_lora_weights.safetensors"
